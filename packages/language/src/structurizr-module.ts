import { type Module, inject } from 'langium';
import { createDefaultModule, createDefaultSharedModule, type DefaultSharedModuleContext, type LangiumServices, type LangiumSharedServices, type PartialLangiumServices } from 'langium/lsp';
import { StructurizrGeneratedModule, StructurizrGeneratedSharedModule } from './generated/module.js';
import { StructurizrValidator, registerValidationChecks } from './structurizr-validator.js';
import { StructurizrNameProvider, StructurizrScopeProvider } from './structurizr-scope.js';
import { StructurizrWorkspaceResolver } from './structurizr-workspace.js';
import { StructurizrCompletionProvider } from './structurizr-completion.js';

/**
 * Declaration of custom services - add your own service classes here.
 */
export type StructurizrAddedServices = {
    workspace: {
        StructurizrWorkspaceResolver: StructurizrWorkspaceResolver
    },
    validation: {
        StructurizrValidator: StructurizrValidator
    }
}

/**
 * Union of Langium default services and your custom services - use this as constructor parameter
 * of custom service classes.
 */
export type StructurizrServices = LangiumServices & StructurizrAddedServices

/**
 * Dependency injection module that overrides Langium default services and contributes the
 * declared custom services. The Langium defaults can be partially specified to override only
 * selected services, while the custom services must be fully specified.
 */
export const StructurizrModule: Module<StructurizrServices, PartialLangiumServices & StructurizrAddedServices> = {
    workspace: {
        StructurizrWorkspaceResolver: (services) => new StructurizrWorkspaceResolver(services)
    },
    references: {
        NameProvider: () => new StructurizrNameProvider(),
        ScopeProvider: (services) => new StructurizrScopeProvider(services)
    },
    lsp: {
        CompletionProvider: (services) => new StructurizrCompletionProvider(services)
    },
    validation: {
        StructurizrValidator: (services) => new StructurizrValidator(services)
    }
};

/**
 * Create the full set of services required by Langium.
 *
 * First inject the shared services by merging two modules:
 *  - Langium default shared services
 *  - Services generated by langium-cli
 *
 * Then inject the language-specific services by merging three modules:
 *  - Langium default language-specific services
 *  - Services generated by langium-cli
 *  - Services specified in this file
 *
 * @param context Optional module context with the LSP connection
 * @returns An object wrapping the shared services and the language-specific services
 */
export function createStructurizrServices(context: DefaultSharedModuleContext): {
    shared: LangiumSharedServices,
    Structurizr: StructurizrServices
} {
    const shared = inject(
        createDefaultSharedModule(context),
        StructurizrGeneratedSharedModule
    );
    const Structurizr = inject(
        createDefaultModule({ shared }),
        StructurizrGeneratedModule,
        StructurizrModule
    );
    shared.ServiceRegistry.register(Structurizr);
    registerValidationChecks(Structurizr);
    if (!context.connection) {
        // We don't run inside a language server
        // Therefore, initialize the configuration provider instantly
        shared.workspace.ConfigurationProvider.initialized({});
    }
    return { shared, Structurizr };
}
